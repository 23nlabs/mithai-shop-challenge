"""Foundation-model inference for the Mithai Shop Challenge (Kaggle GPU).

Runs Yug-1, TimesFM 2.5 and Chronos-Bolt base on every job's history (Competition A input) and on the
calendar-cleaned history (input to the Competition B calendar-correction hybrid). Horizon 56, quantiles
0.1-0.9, ≤2048 days of context. Histories are regenerated by mithai_core and must hash-match the local build.
"""
import json
import time
from pathlib import Path

import numpy as np

import benchmark_core as bc
import mithai_core as mc


def run(model, jobs, field, batch, out, rec):
    n = len(jobs)
    Q = np.full((n, mc.HORIZON, 9), np.nan, dtype=np.float32)
    fail = 0
    t0 = time.perf_counter()
    for i in range(0, n, batch):
        chunk = jobs[i:i + batch]
        try:
            qs = model.forecast([np.asarray(j[field], dtype=float) for j in chunk], mc.HORIZON)
        except Exception as exc:
            rec.append('failures', dict(model=model.name, input=field, keys=[j['key'] for j in chunk], error=repr(exc)[:300]))
            fail += len(chunk)
            continue
        for k, q in enumerate(qs):
            try:
                Q[i + k] = bc.check_forecast(q, mc.HORIZON)
            except Exception as exc:
                # Keep the raw output for disclosed post-hoc analysis; the gate failure is recorded.
                Q[i + k] = np.asarray(q, dtype=np.float32)
                rec.append('failures', dict(model=model.name, input=field, key=chunk[k]['key'], error=repr(exc)[:200]))
                fail += 1
    secs = time.perf_counter() - t0
    np.savez_compressed(Path(out) / f'{model.name}__{field}.npz', q=Q, keys=np.array([j['key'] for j in jobs]))
    rec.log('fm_done', model=model.name, input=field, jobs=n, gate_failures=fail, seconds=secs)


def main(calendar_path, out, weights, expected_sha):
    rec = bc.Recorder(out)
    rec.write('environment.json', bc.environment())
    cal = mc.load_calendar(calendar_path)
    jobs = mc.build_jobs(cal, with_truth=False)
    digest = mc.histories_sha256(jobs)
    rec.log('histories', jobs=len(jobs), sha256=digest, expected=expected_sha, match=digest == expected_sha)
    if digest != expected_sha:
        raise RuntimeError('HISTORY_HASH_MISMATCH: regenerated data differ from the local build')
    loads = {}
    for key in ('chronos-bolt-base', 'timesfm-2.5', 'yug'):
        folder, receipts = bc.download_weights(key, weights)
        t = time.perf_counter()
        model = {'yug': bc.Yug, 'timesfm-2.5': bc.TimesFM, 'chronos-bolt-base': bc.ChronosBolt}[key](folder)
        loads[key] = dict(receipts=receipts, load_seconds=time.perf_counter() - t)
        rec.write('loads.json', loads)
        bc.pilot(model, rec)
        batch = 1 if key == 'yug' else 64  # Yug's sampler stream advances across series inside one call
        for field in ('history', 'history_clean'):
            run(model, jobs, field, batch, out, rec)
        del model
    rec.log('complete')
